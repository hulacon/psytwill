def add_lags(tl: pd.DataFrame) -> pd.DataFrame:
    """``presentation_idx``, ``n_prior``, ``lag_trials``, ``lag_seconds``, ``prev_*``.

    Identity is ``stimulus_id`` alone: the same word in another voice is the
    same item. ``lag_trials`` counts stimulus presentations (rows with an id)
    between the two showings, across everything given. ``lag_seconds`` is the
    onset difference when the previous showing was in the same session and
    run, else NaN — onsets in different runs share no clock.
    """
    tl = tl.copy()
    stim = tl["is_stimulus"].to_numpy()
    pres_idx = np.full(len(tl), np.nan)
    pres_idx[stim] = np.arange(int(stim.sum()))
    tl["presentation_idx"] = pres_idx

    n_prior = np.full(len(tl), np.nan)
    lag_trials = np.full(len(tl), np.nan)
    lag_seconds = np.full(len(tl), np.nan)
    prev_ses: list[Optional[str]] = [None] * len(tl)
    prev_run: list[Optional[str]] = [None] * len(tl)
    last: dict[str, tuple[int, float, str, Optional[str], int]] = {}
    count: dict[str, int] = {}
    for i in np.flatnonzero(stim):
        sid = tl.at[i, "stimulus_id"]
        n_prior[i] = count.get(sid, 0)
        if sid in last:
            p_idx, p_onset, p_ses, p_run, _ = last[sid]
            lag_trials[i] = pres_idx[i] - p_idx
            if p_ses == tl.at[i, "session"] and p_run == tl.at[i, "run"]:
                lag_seconds[i] = float(tl.at[i, "onset"]) - p_onset
            prev_ses[i] = p_ses
            prev_run[i] = p_run
        last[sid] = (pres_idx[i], float(tl.at[i, "onset"]), tl.at[i, "session"], tl.at[i, "run"], i)
        count[sid] = count.get(sid, 0) + 1
    tl["n_prior"] = n_prior
    tl["lag_trials"] = lag_trials
    tl["lag_seconds"] = lag_seconds
    tl["prev_session"] = prev_ses
    tl["prev_run"] = prev_run
    return tl


def load_item_features(
    features_path: str | Path, models: Optional[Sequence[str]] = None
) -> tuple[pd.DataFrame, dict[str, list[str]]]:
    """Item-level rows of a psytwill ``features`` table, pivoted wide.

    Only untimed rows qualify (``time``, ``onset`` and ``offset`` all null):
    a timeline attaches features *of the item*, not of a moment within it.
    Returns the wide frame keyed by ``(stimulus_id, voice)`` and the
    model -> feature-columns map.
    """
    p = Path(features_path)
    if p.suffix == ".parquet":
        long = pd.read_parquet(p)
    else:
        long = pd.read_csv(p)
    need = {"stimulus_id", "model", "feature", "value"}
    if not need <= set(long.columns):
        raise InputError(
            f"{p.name} is not a psytwill features table (needs {sorted(need)}); "
            "build one with `psytwill features`."
        )
    untimed = long
    for col in ("time", "onset", "offset"):
        if col in untimed.columns:
            untimed = untimed[untimed[col].isna()]
    if models:
        unknown = sorted(set(models) - set(untimed["model"].unique()))
        if unknown:
            raise InputError(
                f"models {unknown} have no item-level rows in {p.name}; available: "
                f"{sorted(untimed['model'].unique())}"
            )
        untimed = untimed[untimed["model"].isin(models)]
    if untimed.empty:
        raise InputError(f"{p.name} has no item-level (untimed) feature rows to attach")
    if "voice" not in untimed.columns:
        untimed = untimed.assign(voice=None)
    wide = untimed.pivot_table(
        index=["stimulus_id", "voice"], columns="feature", values="value",
        aggfunc="first", dropna=False,
    ).reset_index()
    wide.columns.name = None
    model_cols = {
        m: sorted(untimed.loc[untimed["model"] == m, "feature"].unique().tolist())
        for m in untimed["model"].unique()
    }
    return wide, model_cols


def attach_features(tl: pd.DataFrame, wide: pd.DataFrame) -> pd.DataFrame:
    """Left-join item features onto the timeline.

    Voice-specific rows (twp1000 audio spaces) join on ``(stimulus_id,
    voice)``; voice-less rows join on ``stimulus_id`` alone. A stimulus row
    with no features in the table keeps NaN — presence is the store's
    statement, not the timeline's.
    """
    feats = [c for c in wide.columns if c not in ("stimulus_id", "voice")]
    voiced = wide[wide["voice"].notna()]
    unvoiced = wide[wide["voice"].isna()].drop(columns=["voice"])
    out = tl.copy()
    if not unvoiced.empty:
        out = out.merge(unvoiced, on="stimulus_id", how="left")
    if not voiced.empty:
        vcols = [c for c in feats if voiced[c].notna().any()]
        v = voiced[["stimulus_id", "voice"] + vcols]
        out = out.merge(v, on=["stimulus_id", "voice"], how="left", suffixes=("", "__voiced"))
        for c in vcols:
            dup = f"{c}__voiced"
            if dup in out.columns:
                out[c] = out[c].where(out[c].notna(), out[dup])
                out = out.drop(columns=[dup])
    return out


def add_context_distance(tl: pd.DataFrame, model: str, cols: Sequence[str], k: int) -> pd.DataFrame:
    """Cosine distance from each item to the mean of the preceding *k* items.

    Context is the preceding *k* stimulus presentations **in the same
    session and run** that carry this model's features; the first item of a
    run has no context and gets NaN. Column: ``ctx_{model}_k{k}_cosdist``.
    """
    if k < 1:
        raise InputError("--context-k must be >= 1")
    missing = [c for c in cols if c not in tl.columns]
    if missing:
        raise InputError(f"model {model!r}: feature columns not attached: {missing[:5]}")
    name = f"ctx_{model}_k{k}_cosdist"
    out = np.full(len(tl), np.nan)
    X = tl[list(cols)].to_numpy(dtype=float)
    for (_, _), idx in tl.groupby(["session", "run"], sort=False, dropna=False).indices.items():
        history: list[np.ndarray] = []
        for i in idx:
            if not tl.at[i, "is_stimulus"]:
                continue
            x = X[i]
            if np.isnan(x).any():
                continue
            if history:
                ctx = np.mean(history[-k:], axis=0)
                denom = np.linalg.norm(x) * np.linalg.norm(ctx)
                out[i] = 1.0 - float(x @ ctx / denom) if denom > 0 else np.nan
            history.append(x)
    tl = tl.copy()
    tl[name] = out
    return tl


