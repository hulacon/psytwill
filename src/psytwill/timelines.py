def build_timeline(
    events: Sequence[str | Path],
    registry_dir: str | Path,
    output: str | Path,
    features: Optional[str | Path] = None,
    models: Optional[Sequence[str]] = None,
    context_model: Optional[str] = None,
    context_k: int = 5,
) -> dict[str, Any]:
    """The ``timelines`` verb: events + registry [+ features] -> one table + sidecar."""
    registry = Registry.from_dir(registry_dir)
    tl = add_lags(read_events(events, registry))

    model_cols: dict[str, list[str]] = {}
    if features is not None:
        wide, model_cols = load_item_features(features, models)
        tl = attach_features(tl, wide)
    if context_model is not None:
        if features is None:
            raise InputError("--context-model needs --features to supply the embedding")
        if context_model not in model_cols:
            raise InputError(
                f"--context-model {context_model!r} is not among the attached models "
                f"{sorted(model_cols)}"
            )
        tl = add_context_distance(tl, context_model, model_cols[context_model], context_k)

    # Fixed columns first, passthrough after, feature columns last.
    passthrough = [
        c for c in tl.columns
        if c not in TIMELINE_COLUMNS and c not in _CONSUMED
        and not any(c in v for v in model_cols.values()) and not c.startswith("ctx_")
    ]
    feature_cols = [c for v in model_cols.values() for c in v if c in tl.columns]
    ctx_cols = [c for c in tl.columns if c.startswith("ctx_")]
    tl = tl[TIMELINE_COLUMNS + passthrough + feature_cols + ctx_cols]

    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.suffix == ".parquet":
        tl.to_parquet(output, index=False)
    elif output.suffix in (".csv", ".tsv"):
        tl.to_csv(output, index=False, sep="\t" if output.suffix == ".tsv" else ",")
    else:
        raise InputError(f"output must be .parquet, .csv or .tsv, got {output.suffix!r}")

    n_stim = int(tl["is_stimulus"].sum())
    meta = {
        "schema_version": TIMELINES_SCHEMA_VERSION,
        "table": "timelines",
        "extractor": "psytwill",
        "extractor_version": __version__,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "output": {
            "path": str(output.resolve()),
            "rows": int(len(tl)),
            "presentations": n_stim,
            "columns": list(tl.columns),
            "key_columns": KEY_COLUMNS,
        },
        "inputs": {
            "events": [str(Path(p).resolve()) for p in events],
            "registry": {"path": str(Path(registry_dir).resolve()), "rows": registry.rows},
            "features": None if features is None else str(Path(features).resolve()),
            "models": sorted(model_cols),
        },
        "context": None if context_model is None else {"model": context_model, "k": context_k},
        "sets": tl.loc[tl["is_stimulus"], "stimulus_set"].value_counts().to_dict(),
        "time_semantics": "experimental time: onsets as recorded in events.tsv; "
        "lag_seconds only within one run; no HRF, no TR (Contract C).",
    }
    meta_path = output.with_suffix(".meta.json")
    with open(meta_path, "w") as f:
        json.dump(meta, f, indent=2)
    return {
        "output": str(output),
        "meta_path": str(meta_path),
        "rows": int(len(tl)),
        "presentations": n_stim,
        "sets": meta["sets"],
        "models": sorted(model_cols),
    }
